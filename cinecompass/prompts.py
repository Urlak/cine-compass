"""Промпты для LLM-задач (статистика, профайл, рекомендации)."""

STYLE = (
    "Отвечай на русском языке в формате Markdown. "
    "Указывай участников по названиям фильмов/сериалов, людей — по именам; "
    "технические ID никогда не упоминай в итоговом тексте. "
    "Опирайся только на полученные данные, не выдумывай факты о записях, "
    "которых нет в списке."
)


def stats_prompt(rows: str, overview: str) -> str:
    return f"""Ты аналитик кинопортретов. Ниже — полная история просмотров и оценивания зрителя
(личная оценка от 1 до 10, дата просмотра, жанры и прочее).

Сводка, посчитанная программно:
{overview}

Полный список (одно просмотренное название — одна строка):
{rows}

Составь глубокий аналитический отчёт:
1. Что зритель любит больше всего (жанры, эпохи, режиссёры, типы: кино/сериалы) — с числами.
2. Как устроена система оценок: за что ставит высокие, за что — низкие.
3. Аномалии и неожиданные факты в поведении.
4. Активность по годам и изменения вкусов со временем.
5. Короткий вывод «почерк зрителя» в 3-4 предложениях.

{STYLE}"""


def profile_prompt(rows: str, overview: str) -> str:
    return f"""Ты составляешь «портрет зрителя» для персонального кинорекомендательного сервиса.
Ниже — история его просмотров и оценок.

Сводка, посчитанная программно:
{overview}

Полный список:
{rows}

Напиши профайл зрителя:
1. Краткое «вкусовое ядро»: что предсказуемо понравится.
2. Любимые режиссёры, жанры и эпохи (с примерами названий).
3. «Красные флаги» — что он обычно не любит.
4. Как он смотрит: когда, сколько, как оценивает.
5. Наконец, «формула вкуса» одним предложением и 5 ключевых вкусовых признаков.

Всюду, где упоминаешь фильм или сериал, давай связку «Русское название» (Original Title),
беря оригинальное название из списка.

{STYLE}"""


def predict_prompt(rows: str, overview: str, title: str) -> str:
    return f"""Ты киновед, знающий вкус зрителя вдоль и поперёк. Ниже — сводка и полная
история его просмотров и оценок.

Сводка:
{overview}

Полная история:
{rows}

Зритель спрашивает: «{title}».

Отвечай кратко, строго в этом формате:
1. Если фильм или сериал уже в его списке — скажи это сразу: реальная личная оценка
   из списка и дата просмотра, прогноз не нужен.
2. Если записи нет — прогноз: «Оценка: X/10» (целое число) и «Почему: …» — 2-3 предложения
   с опорой на конкретные соседние по вкусу названия из его истории (что любил, что забраковал).
   Упоминать можно жанр, режиссёра, актёров, эпоху, настроение. СЮЖЕТ НЕ РАСКРЫВАТЬ:
   никаких завязок, поворотов и концовок.
   Названия фильмов пиши как «Русское название» (Original Title), беря оригинал
   из списка.

Отвечай на русском, коротким Markdown-блоком."""


RECOMMEND_MODES = {
    "old": (
        "Любимое из старого",
        "Нужно предложить фильмы/сериалы, которые зритель воспримет как '\"родные\" и проверенные временем: высоко личные оценки, сильные эмоциональные привязки. Можно предложить и пересмотр любимого, если он для этого зрителя особенно ценен.",
    ),
    "new": (
        "Свежее и новенькое",
        "Нужно предложить к просмотру что-то из последних лет (или недавно оценённых), что соответствует его вкусу: свежие хиты, продолжения любимых франшиз, новинки в любимых жанрах.",
    ),
    "classics": (
        "Хорошее старое",
        "Нужно предложить классику, которую зритель ещё не видел или вероятно недооценил, в жанрах/эпохах, которые он любит: старые, но сильные тайтлы.",
    ),
}


def recommend_prompt(rows: str, overview: str, mode: str, count: int) -> tuple[str, str]:
    title, direction = RECOMMEND_MODES[mode]
    prompt = f"""Ты персональный кинокуратор зрителя с 10-летним стажем переписки с ним.
Его вкус ты знаешь. Ниже — сводка вкуса и вся история оценок.

Сводка:
{overview}

Полная история:
{rows}

Задача: «что посмотреть прямо сейчас». {direction}
Подбери {count} тайтлов строго из его библиотеки (кроме режима classics: там можно
предлагать и не отслеживаемое им, если это очень похоже на его вкус).

Для каждого тайтла верни блок:
- **Название (год)** — жанр, личная оценка (если есть)
  - «Почему сейчас»: персональная причина, привязанная к его вкусу и настроению.
  - «Что подготовиться»: подсказка, чем смотреть (время суток, закуски, компания).

Учти режим: {title}. Объяснение должно быть тёплым, конкретным и смешным по вкусу зрителя, не вычурным.

{STYLE}"""
    return title, prompt
