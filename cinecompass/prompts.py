"""Промпты для LLM-задач (статистика, профайл, рекомендации)."""

STYLE = (
    "Отвечай на русском языке в формате Markdown. "
    "Указывай участников по названиям фильмов/сериалов, людей — по именам; "
    "технические ID никогда не упоминай в итоговом тексте. "
    "Опирайся только на полученные данные, не выдумывай факты о записях, "
    "которых нет в списке."
)


def stats_prompt(context: str) -> str:
    return f"""Ты аналитик кинопортретов. Ниже — программно рассчитанная сводка истории
просмотров и оценивания зрителя (личная оценка от 1 до 10, дата просмотра, жанры и прочее).

{context}

Составь глубокий аналитический отчёт:
1. Что зритель любит больше всего (жанры, эпохи, режиссёры, типы: кино/сериалы) — с числами.
2. Как устроена система оценок: за что ставит высокие, за что — низкие.
3. Аномалии и неожиданные факты в поведении.
4. Активность по годам и изменения вкусов со временем.
5. Короткий вывод «почерк зрителя» в 3-4 предложениях.

Жёсткие правила:
- Не пересчитывай статистику самостоятельно: все числа уже посчитаны в сводке,
  используй их как есть.
- Не выдумывай закономерности и причинно-следственные связи, которых не видно в числах
  сводки; аномалии ищи прежде всего в готовых списках оценок 10 и «5 и ниже».
- Учитывай раздел «Полнота метаданных»: статистика по режиссёрам и странам описывает
  только заполненную часть библиотеки, а не её целиком.
- Не описывай семантические предпочтения по тегам — это предмет другого отчёта
  (Taste Profile), в сводке их нет.

{STYLE}"""


def profile_prompt(taste_profile_md: str) -> str:
    return f"""Ты составляешь «портрет зрителя» для персонального кинорекомендательного сервиса.
Ниже — программно рассчитанный Taste Profile: Approval Rate и Lift семантических тегов по
четырём корзинам оценок (9–10, 8, 6–7, 1–5), нишевые теги, контрастные пары тегов и
фактологические срезы (десятилетия, режиссёры, расхождение с рейтингом Кинопоиска).

{taste_profile_md}

Составь профиль строго из шести секций — с этими заголовками, в этом порядке. Целевой
объём всего документа — 1200–1600 токенов.

## 0. Snapshot
Покрытие данных (tagged/rated), распределение оценок по корзинам, пиковые и провальные
десятилетия, любимые режиссёры, аномалии против рейтинга Кинопоиска.

## 1. Core Drivers
3–4 смысловых кластера тегов с максимальным Lift: механика («почему это заходит») и
2–3 фильма-якоря с оценкой [9] или [10].

## 2. Conditional Rules (IF / THEN)
Правила для конфликтных тегов (period, satirical, ensemble, urban и другие из секций
пар) вида: «IF period AND family THEN …» — чем объясняется провал и что разрешает
конфликт. Опирайся на пары с минимальным одобрением.

## 3. Hard Red Flags
Комбинации, стабильно уводящие оценку в 1–5 или в скучные 6, с примерами [оценка].
Опирайся на высокий approval_1_5 и низкий Lift.

## 4. Rating Calibration
Чем для этого зрителя отличаются 9–10, 8 и 6–7: по 3 якорных фильма на каждый диапазон
из входных данных.

## 5. Exploration Vectors
Ниши для добора (высокий Lift при малом n из секции нишевых тегов) и соседние жанровые
территории — заготовки для рекомендаций.

Жёсткие правила:
- Только эти шесть секций; никаких вводных и заключительных абзацев.
- Не пиши «вероятно», «похоже, что», «указывает на то, что», не рассуждай о размере
  выборки и качестве данных — все оговорки уже есть в Taste Profile.
- Каждый тезис подтверждай конкретными фильмами из входа с годом и оценкой [N];
  тезис без фильма-примера не пиши.
- Не пересчитывай статистику: все числа уже посчитаны, используй как есть.
- Не путай распространённость тега с предпочтением: смотри на Lift, а не на n.
- Не придумывай психологические характеристики зрителя за пределами данных.
- Всюду, где упоминаешь фильм или сериал, давай связку «Русское название» (Original
  Title, год) [оценка], как в отчёте.

{STYLE}"""


def predict_prompt(profile_md: str, neighbours_rows: str, target: str) -> str:
    return f"""Ты киновед, знающий вкус зрителя вдоль и поперёк. Вкус описан программно
рассчитанным Taste Profile, а ниже — его LLM-портрет и ближайшие к целевому
фильму записи его истории с личными оценками.

## Портрет зрителя

{profile_md}

## Ближайшие соседи по вкусу

{neighbours_rows}

Зритель спрашивает: «{target}».

Отвечай кратко, строго в этом формате:
1. Прогноз: «Оценка: X/10» (целое число) и «Почему: …» — 2-3 предложения
   с опорой на конкретные соседние по вкусу названия из его истории (что любил, что забраковал).
   Упоминать можно жанр, режиссёра, актёров, эпоху, настроение. СЮЖЕТ НЕ РАСКРЫВАТЬ:
   никаких завязок, поворотов и концовок.
   Названия фильмов пиши как «Русское название» (Original Title), беря оригинал
   из списка соседей.

Отвечай на русском, коротким Markdown-блоком."""


RECOMMEND_MODES = {
    "old": (
        "Любимое из старого",
        "Нужно предложить фильмы/сериалы, которые зритель воспримет как '\"родные\" и проверенные временем: высоко личные оценки, сильные эмоциональные привязки. Можно предложить и пересмотр любимого, если он для этого зрителя особенно ценен.",
    ),
    "new": (
        "Свежее и новенькое",
        "Нужно предложить к просмотру что-то из последних лет (или недавно оценённых), что соответствует его вкусу: свежие хиты, продолжения любимых франшиз, новинки в любимых жанрах.",
    ),
    "classics": (
        "Хорошее старое",
        "Нужно предложить классику, которую зритель ещё не видел или вероятно недооценил, в жанрах/эпохах, которые он любит: старые, но сильные тайтлы.",
    ),
}


def recommend_prompt(candidates: str, profile_md: str, mode: str, count: int) -> tuple[str, str]:
    title, direction = RECOMMEND_MODES[mode]
    prompt = f"""Ты персональный кинокуратор зрителя. Вкус зрителя описан программно
рассчитанным Taste Profile, а список кандидатов на сегодня отобран программно
по режиму «{title}».

## Taste Profile

{profile_md}

## Кандидаты

{candidates}

Задача: «что посмотреть прямо сейчас». {direction}
Подбери {count} тайтлов строго из списка кандидатов (кроме режима classics: там можно
предлагать и не отслеживаемое им, если это очень похоже на его вкус).

Правила:
- Кандидаты без тегов — полноценные участники отбора: теги есть не у всех записей,
  их отсутствие не означает, что фильм не по вкусу зрителю.
- Не путай распространённость тега с предпочтением: частый тег в Taste Profile —
  не критерий отбора сам по себе.
- Красные флаги применяй мягко: низко оценённый срез в Taste Profile мал,
  массово отсеивать кандидатов по нему нельзя.
- Опирайся только на Taste Profile и данные кандидатов, не выдумывай факты о фильмах.

Для каждого тайтла верни блок:
- **Название (год)** — жанр, личная оценка (если есть)
  - «Почему сейчас»: персональная причина, привязанная к его вкусу и настроению.
  - «Что подготовиться»: подсказка, чем смотреть (время суток, закуски, компания).

Учти режим: {title}. Объяснение должно быть тёплым, конкретным и смешным по вкусу зрителя, не вычурным.

{STYLE}"""
    return title, prompt
